/* The token roster as data, and the comparison migrations.json is checked with.
 *
 * A migration manifest that goes stale is worse than no manifest, because the
 * tooling built on it will be trusted. So the manifest is not allowed to be
 * hand-maintained on its own: `migrations.test.mjs` derives what CHANGED in the
 * stylesheets and refuses to pass unless every change is named by an entry.
 *
 * "Changed" needs a previous state to be measured against, and there is nowhere
 * hermetic to get one — the published tarball needs the network, and git needs
 * a full clone. So the previous state is committed, in src/token-baseline.json,
 * and moved forward by hand with scripts/accept-token-baseline.mjs. That is a
 * snapshot, with a snapshot's weakness: an author who runs the accept script
 * without writing the entries silences the check. What it buys is that the
 * silencing is a diff in a reviewed file rather than an omission nobody sees,
 * which is the same trade the visual baselines in this repo already make.
 *
 * Authored as .mjs to match its neighbours: the accept script runs it under
 * plain node, before any build step.
 */

import { parseTokensCss } from './parse-tokens-css.mjs';

/**
 * Every `:root` token, name to DECLARED value, last declaration winning the way
 * CSS does.
 *
 * Declared and not resolved, on purpose. `--status-success: var(--anchor-500)`
 * becoming `--status-success: oklch(51.9% 0.145 150)` is a change of wiring and
 * is exactly what a consumer has to hear about. A tweak to `--anchor-500`
 * underneath is a change of shade — already measured by contrast.test.mjs — and
 * resolving would make it look as though every token downstream of it had been
 * migrated, which would bury the real entries in noise.
 *
 * @param {string | string[]} css the token stylesheets, in cascade order
 * @returns {Record<string, string>}
 */
export function tokenRoster(css) {
  const roster = {};
  for (const token of parseTokensCss(css)) roster[token.name] = token.value;
  return roster;
}

/**
 * What moved between a baseline roster and the current one.
 *
 * Additions are not returned. A token that did not exist cannot have a call
 * site, so there is nothing for a consumer to migrate and nothing for the
 * manifest to say — the palette release added 29 tokens and not one of them
 * needs an entry.
 *
 * @param {Record<string, string>} before
 * @param {Record<string, string>} after
 * @returns {{removed: string[], repointed: string[]}}
 */
export function rosterDrift(before, after) {
  const removed = [];
  const repointed = [];

  for (const [name, value] of Object.entries(before)) {
    if (!(name in after)) removed.push(name);
    else if (after[name] !== value) repointed.push(name);
  }

  return { removed, repointed };
}

/** The committed file's shape. Two decimals of prose so a reader of the raw
 *  JSON knows what it is for and that editing it by hand is not the move. */
export function serializeTokenBaseline(css) {
  return `${JSON.stringify(
    {
      $comment:
        'The token roster the migration manifest is checked against. Generated by scripts/accept-token-baseline.mjs — do not edit by hand. Moving it forward is how you declare that migrations.json accounts for everything that changed.',
      tokens: tokenRoster(css),
    },
    null,
    2,
  )}\n`;
}
